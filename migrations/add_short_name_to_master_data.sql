-- Step 1: Add short_name column to all master data tables
ALTER TABLE categories ADD COLUMN IF NOT EXISTS short_name TEXT;
ALTER TABLE brands ADD COLUMN IF NOT EXISTS short_name TEXT;
ALTER TABLE main_products ADD COLUMN IF NOT EXISTS short_name TEXT;
ALTER TABLE variants ADD COLUMN IF NOT EXISTS short_name TEXT;
ALTER TABLE specifications ADD COLUMN IF NOT EXISTS short_name TEXT;
ALTER TABLE sizes ADD COLUMN IF NOT EXISTS short_name TEXT;
ALTER TABLE units ADD COLUMN IF NOT EXISTS short_name TEXT;

-- Step 2: Create function to generate short name (PostgreSQL version)
-- This replicates the TypeScript generateShortName() logic
CREATE OR REPLACE FUNCTION generate_short_name(p_name TEXT)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
  v_short_name TEXT;
  v_words TEXT[];
  v_word TEXT;
  v_result TEXT := '';
BEGIN
  -- Handle empty input
  IF p_name IS NULL OR LENGTH(TRIM(p_name)) = 0 THEN
    RETURN NULL;
  END IF;
  
  -- Remove common words and clean the string
  v_short_name := UPPER(TRIM(p_name));
  v_short_name := REGEXP_REPLACE(v_short_name, '\b(DAN|ATAU|YANG|DENGAN|KE|DARI|DI|UNTUK|THE|AND|OR|OF|TO|FROM|IN|FOR)\b', '', 'gi');
  
  -- Split by spaces and take first letter of each word
  v_words := STRING_TO_ARRAY(TRIM(v_short_name), ' ');
  
  FOREACH v_word IN ARRAY v_words
  LOOP
    IF LENGTH(TRIM(v_word)) > 0 THEN
      v_result := v_result || LEFT(TRIM(v_word), 1);
    END IF;
  END LOOP;
  
  -- If result is too short or empty, take first 3 characters
  IF LENGTH(v_result) = 0 THEN
    v_result := UPPER(LEFT(REGEXP_REPLACE(p_name, '[^A-Za-z0-9]', '', 'g'), 3));
  END IF;
  
  RETURN v_result;
END;
$$;

-- Step 3: Populate short_name for existing data using auto-generate algorithm
UPDATE categories SET short_name = generate_short_name(name) WHERE short_name IS NULL;
UPDATE brands SET short_name = generate_short_name(name) WHERE short_name IS NULL;
UPDATE main_products SET short_name = generate_short_name(name) WHERE short_name IS NULL;
UPDATE variants SET short_name = generate_short_name(name) WHERE short_name IS NULL;
UPDATE specifications SET short_name = generate_short_name(name) WHERE short_name IS NULL;
UPDATE sizes SET short_name = generate_short_name(name) WHERE short_name IS NULL;
UPDATE units SET short_name = generate_short_name(name) WHERE short_name IS NULL;

