COMMENT ON FUNCTION generate_short_name(TEXT) IS 'Generates short name from full name. Used as default suggestion when creating new master data.';

-- Step 5: Create indexes for better query performance
CREATE INDEX IF NOT EXISTS idx_categories_short_name ON categories(short_name);
